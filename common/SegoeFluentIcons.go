package common

import (
	"github.com/famei/gofluent/resources"
	"github.com/mappu/miqt/qt"
)

func SegoeFluentInit() {
	fontId := qt.QFontDatabase_AddApplicationFontFromData(resources.SegoeFluentIcons)
	fontFamilies := qt.QFontDatabase_ApplicationFontFamilies(fontId)
	lightColor = qt.NewQColor3(0, 0, 0)
	darkColor = qt.NewQColor3(255, 255, 255)
	FluentIconFont = qt.NewQFont2(fontFamilies[0])
	FluentIconFont.SetBold(false)
}

type SegoeFluentIcon string

var FluentIconFont *qt.QFont
var lightColor *qt.QColor
var darkColor *qt.QColor

func (f SegoeFluentIcon) Path(theme Theme) string {
	return ""
}

func (f SegoeFluentIcon) iconColor(theme Theme) *qt.QColor {
	if resolvedTheme(theme) == ThemeDark {
		return darkColor
	}
	return lightColor
}

func (f SegoeFluentIcon) RenderGlyph(painter *qt.QPainter, rect *qt.QRectF, theme Theme, color *qt.QColor) {
	if FluentIconFont == nil {
		SegoeFluentInit()
	}
	// The glyph is drawn with the icon font and its own pen/brush, so the whole
	// painter state is saved and restored: a caller that draws text right after
	// the icon (the command bar's buttons, for one) would otherwise inherit the
	// icon font — which has no Latin glyphs — and lose its label.
	painter.Save()
	defer painter.Restore()

	FluentIconFont.SetPixelSize(int(rect.Height()))
	painter.SetFont(FluentIconFont)
	painter.SetPenWithStyle(qt.NoPen)
	var brush *qt.QBrush
	if color != nil {
		brush = qt.NewQBrush3(color)
	} else {
		brush = qt.NewQBrush3(f.iconColor(theme))
	}

	// The painter copies the brush on setBrush, so the temporary is released here
	// (Restore still runs last, because defers unwind in reverse order).
	defer brush.Delete()
	painter.SetBrush(brush)
	painter.SetRenderHints(qt.QPainter__Antialiasing | qt.QPainter__TextAntialiasing)

	path := qt.NewQPainterPath()
	defer path.Delete()
	path.AddText2(rect.X(), rect.Y()+rect.Height(), FluentIconFont, string(f))
	painter.DrawPath(path)
}

func (f SegoeFluentIcon) renderIcon(theme Theme, color *qt.QColor) *qt.QIcon {
	const size = 128
	pm := qt.NewQPixmap2(size, size)
	transparent := qt.NewQColor11(0, 0, 0, 0)
	pm.FillWithFillColor(transparent)
	transparent.Delete()

	painter := qt.NewQPainter2(pm.QPaintDevice)
	f.RenderGlyph(painter, qt.NewQRectF4(0, 0, size, size), theme, color)
	painter.End()
	painter.Delete()

	return qt.NewQIcon2(pm)
}

func (f SegoeFluentIcon) Icon(theme Theme) *qt.QIcon {
	return f.renderIcon(theme, nil)
}
func (f SegoeFluentIcon) Colored(light, dark *qt.QColor) *ColoredFluentIcon {
	return &ColoredFluentIcon{fluentIcon: f, lightColor: light, darkColor: dark}
}

func (f SegoeFluentIcon) Render(painter *qt.QPainter, rect *qt.QRectF, theme Theme) {
	f.RenderGlyph(painter, rect, theme, nil)
}

func (f SegoeFluentIcon) QIcon(reverse bool) *qt.QIcon {
	lc, dc := darkColor, lightColor
	if reverse {
		lc, dc = lightColor, darkColor
	}
	if !IsDarkTheme() {
		return f.renderIcon(ThemeAuto, dc)
	}
	return f.renderIcon(ThemeAuto, lc)
}

